-- HumanMesh AI Help and private app-support reports.
-- Apply after the existing migrations. Never put the service-role or OpenAI key in Android code.

create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('bug', 'account', 'feature_request', 'safety', 'other')),
  title text not null check (char_length(title) between 5 and 120),
  description text not null check (char_length(description) between 10 and 3000),
  status text not null default 'open' check (status in ('open', 'reviewing', 'resolved', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists support_tickets_user_recent_idx on public.support_tickets (user_id, created_at desc);
create index if not exists support_tickets_status_recent_idx on public.support_tickets (status, created_at desc);

alter table public.support_tickets enable row level security;
drop policy if exists support_tickets_insert_own on public.support_tickets;
create policy support_tickets_insert_own on public.support_tickets for insert to authenticated
  with check (user_id = auth.uid());
drop policy if exists support_tickets_select_own on public.support_tickets;
create policy support_tickets_select_own on public.support_tickets for select to authenticated
  using (user_id = auth.uid());
grant insert, select on public.support_tickets to authenticated;
revoke all on public.support_tickets from anon;

-- Server-only usage ledger. Clients cannot read or write it directly.
create table if not exists public.ai_help_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists ai_help_usage_user_recent_idx on public.ai_help_usage (user_id, created_at desc);
alter table public.ai_help_usage enable row level security;
revoke all on public.ai_help_usage from public, anon, authenticated;

-- Atomically limits one account to 8 prompts/minute and 60 prompts/day.
create or replace function public.consume_humanmesh_ai_help_quota(p_user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $quota$
declare
  per_minute integer;
  per_day integer;
begin
  if p_user_id is null then return false; end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_user_id::text, 0));

  select
    count(*) filter (where created_at > pg_catalog.now() - interval '1 minute'),
    count(*) filter (where created_at > pg_catalog.now() - interval '24 hours')
  into per_minute, per_day
  from public.ai_help_usage
  where user_id = p_user_id
    and created_at > pg_catalog.now() - interval '24 hours';

  if per_minute >= 8 or per_day >= 60 then return false; end if;
  insert into public.ai_help_usage (user_id) values (p_user_id);
  return true;
end;
$quota$;

revoke all on function public.consume_humanmesh_ai_help_quota(uuid) from public, anon, authenticated;
grant execute on function public.consume_humanmesh_ai_help_quota(uuid) to service_role;
